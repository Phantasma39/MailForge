// ============================================================================
//  utils.h —— 公共工具函数声明
//
//  这个头文件放一些"跟业务无关、哪里都能用"的小工具，
//  目前只有一个：去除字符串首尾的空格和换行（trim）。
// ============================================================================
#ifndef UTILS_H
#define UTILS_H

#include <string>

// 服务器监听端口（用 8888，避开系统保留端口）
// 8888 是常见的开发测试端口，普通用户即可绑定，不需要 root 权限
#define SERVER_PORT 8888

// 接收缓冲区大小
// recv() 一次最多读 BUFFER_SIZE 字节；4096 = 4KB，
// 对 HTTP 请求来说足够用了（请求行一般只有几百字节）
#define BUFFER_SIZE 4096

// 工具函数：去除字符串首尾的空格 / 制表符 / 回车 / 换行
// 网络数据经常带着 \r\n 结尾，直接比较字符串会失败，所以先 trim 一下再处理。
// 参数用 const 引用：只读，且避免整个字符串的拷贝开销
std::string trim(const std::string& str);

#endif
